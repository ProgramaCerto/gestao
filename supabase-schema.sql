--------------------------------------------------------------------------------
-- POLÍTICAS RLS (FOR ALL, USING (true), WITH CHECK (true)) EM TODAS AS TABELAS
--------------------------------------------------------------------------------

DO $$ 
DECLARE 
    tbl TEXT;
    public_tables TEXT[] := ARRAY[
        'usuarios',
        'cursos',
        'cursos_concluidos',
        'aulas_dos_cursos',
        'aulas_concluidas',
        'modulos',
        'projetos_progresso',
        'trilha_de_estudo',
        'atendimentos',
        'documentos',
        'pastas',
        'notificacoes',
        'ocorrencias',
        'projetos',
        'codigo_projetos'
    ];
    studio_tables TEXT[] := ARRAY[
        'projetos',
        'pastas',
        'codigo_projetos'
    ];
BEGIN
    FOREACH tbl IN ARRAY public_tables LOOP
        IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'public' AND tablename = tbl) THEN
            EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', tbl);
            EXECUTE format('DROP POLICY IF EXISTS "all_true_%I" ON public.%I;', tbl, tbl);
            EXECUTE format('DROP POLICY IF EXISTS "Acesso total publico e autenticado %I" ON public.%I;', tbl, tbl);
            EXECUTE format('
                CREATE POLICY "all_true_%I" 
                ON public.%I 
                FOR ALL 
                USING (true) 
                WITH CHECK (true);
            ', tbl, tbl);
        END IF;
    END LOOP;

    FOREACH tbl IN ARRAY studio_tables LOOP
        IF EXISTS (SELECT FROM pg_tables WHERE schemaname = 'studio' AND tablename = tbl) THEN
            EXECUTE format('ALTER TABLE studio.%I ENABLE ROW LEVEL SECURITY;', tbl);
            EXECUTE format('DROP POLICY IF EXISTS "all_true_studio_%I" ON studio.%I;', tbl, tbl);
            EXECUTE format('
                CREATE POLICY "all_true_studio_%I" 
                ON studio.%I 
                FOR ALL 
                USING (true) 
                WITH CHECK (true);
            ', tbl, tbl);
        END IF;
    END LOOP;
END $$;
